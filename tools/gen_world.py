def render_world(room, model, spec, debug_plane):
    phys = (spec or {}).get("physics", {})
    ground = ""
    if debug_plane:
        r = (spec or {}).get("room", {})
        size = max(float(r.get("length", 10.0)), float(r.get("width", 10.0))) + 2.0
        ground = DEBUG_GROUND_PLANE.format(size=f"{size:.2f}")
    return WORLD_TEMPLATE.format(
        room=room,
        when=time.strftime("%Y-%m-%d %H:%M:%S"),
        world_name=model,
        room_model=model,
        # Carried from follow_target.sdf. Held identical across branches by construction.
        max_step_size=phys.get("max_step_size", 0.005),
        real_time_factor=phys.get("real_time_factor", 1.0),
        debug_ground_plane=ground,
    )


def check_branches(a_path, b_path):
    """Confirm the two worlds differ only in which model they include."""
    if not (a_path.is_file() and b_path.is_file()):
        die("both worlds must exist before --check; generate them with --branch both")
    a = a_path.read_text().splitlines()
    b = b_path.read_text().splitlines()
    diff = [
        ln
        for ln in difflib.unified_diff(a, b, a_path.name, b_path.name, lineterm="", n=0)
        if ln.startswith(("+", "-")) and not ln.startswith(("+++", "---"))
    ]
    # Expected: the <uri> line, the <world name> line, and the generated-on comment.
    allowed = ("<uri>model://", "<world name=", "GENERATED by tools/gen_world.py")
    unexpected = [ln for ln in diff if not any(k in ln for k in allowed)]

    print(f"\n{len(diff)} differing lines between the two branch worlds:")
    for ln in diff:
        print("   " + ln)
    if unexpected:
        print(
            "\nFAIL: the branches differ in something other than the room model.\n"
            "      The comparison no longer isolates photogrammetry -- fix the template "
            "and regenerate both.\n",
            file=sys.stderr,
        )
        return 1
    print("\nOK: the branches differ only in the model they include.\n")
    return 0


