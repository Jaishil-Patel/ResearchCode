FLOOR_COLOUR = "0.55 0.52 0.48 1"
WALL_COLOUR = "0.85 0.85 0.82 1"
CEILING_COLOUR = "0.90 0.90 0.90 1"
FURNITURE_COLOUR = "0.45 0.38 0.30 1"


def fmt3(v):
    return " ".join(f"{float(x):.4f}" for x in v)


def box(name, centre, size, colour, mu, mu2, yaw=0.0):
    return BOX.format(
        name=name,
        pose=f"{fmt3(centre)} 0 0 {float(yaw):.4f}",
        size=fmt3(size),
        colour=colour,
        mu=mu,
        mu2=mu2,
    )


def cylinder(name, centre, diameter, height, colour, mu, mu2):
    # SDF cylinders stand along the local z axis, so no yaw: a round footprint has none.
    return CYLINDER.format(
        name=name,
        pose=f"{fmt3(centre)} 0 0 0",
        radius=f"{float(diameter) / 2.0:.4f}",
        length=f"{float(height):.4f}",
        colour=colour,
        mu=mu,
        mu2=mu2,
    )


def furniture_shape(f, name):
    """'box' (default) or 'cylinder'. A cylinder's size is [diameter, diameter, height] --
    kept as a 3-vector so every consumer that only wants a bounding box still gets one."""
    shape = str(f.get("shape", "box")).lower()
    if shape not in ("box", "cylinder"):
        die(f"furniture '{name}': shape must be 'box' or 'cylinder', not '{shape}'")
    if shape == "cylinder":
        sx, sy = (float(v) for v in f["size"][:2])
        if abs(sx - sy) > 1e-6:
            die(f"furniture '{name}': a cylinder needs size [d, d, h] with equal x and y "
                f"(got {sx} and {sy}); SDF has no elliptical cylinder")
    return shape


def load_spec(path):
    try:
        import yaml
    except ImportError:
        die("PyYAML is not installed:  pip3 install pyyaml")
    if not path.is_file():
        die(
            f"no room spec at {path}\n"
            f"Copy {GT_DIR / 'TEMPLATE_spec.yaml'} to {path.name} and fill it in from "
            f"the tape measurements in the matching .csv."
        )
    spec = yaml.safe_load(path.read_text()) or {}
    room = spec.get("room")
    if not room:
        die(f"{path}: missing top-level 'room:' block")
    for key in ("length", "width", "height"):
        if not room.get(key):
            die(f"{path}: room.{key} is required and must be non-zero")
    room.setdefault("wall_thickness", 0.10)
    room.setdefault("floor_thickness", 0.05)
    room.setdefault("include_ceiling", True)
    spec["room"] = room
    spec.setdefault("openings", [])
    spec.setdefault("furniture", [])
    return spec


def wall_segments(wall, room, openings):
    """Geometry for one wall, split around any openings in it.

    Returns a list of (name, centre_xyz, size_xyz) tuples -- pure geometry, not SDF. Two
    consumers need exactly the same segments and must never compute them independently:
    `build_standard_model` renders each into a <collision>/<visual> box pair for the SDF,
    and `rl/env/routes.py` rasterises the same boxes into the 2D occupancy grid that plans
    l* (Eq. 4.3) for BOTH branches. If the two ever used different wall geometry, l* would
    describe a room slightly different from the one either policy is scored in.

    The interior of the room is x in [0, length], y in [0, width], floor at z = 0 -- the
    same frame mesh_import.py puts the reconstruction in with its default
    --origin-mode floor-min-corner. If those two disagree, the branches are not the same
    room and no comparison between them means anything.
    """
    L, W, H = room["length"], room["width"], room["height"]
    t = room["wall_thickness"]

    if wall in ("x_min", "x_max"):
        # Long axis is y, extended by t at each end so the corners are filled.
        axis_lo, axis_hi = -t, W + t
        fixed = -t / 2.0 if wall == "x_min" else L + t / 2.0

        def make(a0, a1, z0, z1, name):
            return (name, (fixed, (a0 + a1) / 2.0, (z0 + z1) / 2.0),
                    (t, a1 - a0, z1 - z0))

    else:
        axis_lo, axis_hi = 0.0, L
        fixed = -t / 2.0 if wall == "y_min" else W + t / 2.0

        def make(a0, a1, z0, z1, name):
            return (name, ((a0 + a1) / 2.0, fixed, (z0 + z1) / 2.0),
                    (a1 - a0, t, z1 - z0))

    mine = sorted(
        (o for o in openings if o.get("wall") == wall), key=lambda o: float(o["start"])
    )
    if not mine:
        return [make(axis_lo, axis_hi, 0.0, H, wall)]

    out = []
    cursor = axis_lo
    for i, o in enumerate(mine):
        s_, e_ = float(o["start"]), float(o["end"])
        b, top = float(o.get("bottom", 0.0)), float(o.get("top", H))
        label = o.get("name") or f"opening{i}"
        if not (axis_lo <= s_ < e_ <= axis_hi):
            die(f"opening '{label}' on {wall}: start/end {s_}..{e_} outside {axis_lo}..{axis_hi}")
        if s_ > cursor:
            out.append(make(cursor, s_, 0.0, H, f"{wall}_{i}_before"))
        if b > 0.0:
            out.append(make(s_, e_, 0.0, b, f"{wall}_{label}_sill"))
        if top < H:
            out.append(make(s_, e_, top, H, f"{wall}_{label}_lintel"))
        cursor = e_
    if cursor < axis_hi:
        out.append(make(cursor, axis_hi, 0.0, H, f"{wall}_last"))
    return out


def standard_room_obstacles(spec):
    """Every wall segment and furniture box, as pure geometry, for the standard branch.

    This is what `rl/env/routes.py` plans l* on (see the decision recorded there): the
    tape-measured geometry is metrically exact and identical for both branches by
    construction, unlike the photogrammetric mesh, which can have reconstruction holes
    or debris that would distort l* differently for whichever branch it was computed
    against. Floor and ceiling are deliberately excluded -- they bound the room, they are
    not obstacles a 2D navigation grid needs to avoid.

    Returns a list of dicts: {"name", "centre": (x, y, z), "size": (sx, sy, sz),
    "yaw": radians, "shape": "box" | "cylinder"}. A cylinder's size is
    (diameter, diameter, height) and its yaw is always 0.
    """
    room = spec["room"]
    obstacles = []
    for wall in WALLS:
        for name, centre, size in wall_segments(wall, room, spec["openings"]):
            obstacles.append({"name": name, "centre": centre, "size": size, "yaw": 0.0,
                              "shape": "box"})
    for i, f in enumerate(spec["furniture"]):
        name = f.get("name") or f"furniture{i}"
        shape = furniture_shape(f, name)
        sx, sy, sz = (float(v) for v in f["size"])
        pose = [float(v) for v in f["pose"]]
        yaw = pose[3] if len(pose) == 4 and shape == "box" else 0.0
        obstacles.append({"name": name, "centre": tuple(pose[:3]),
                          "size": (sx, sy, sz), "yaw": yaw, "shape": shape})
    return obstacles


def build_standard_model(spec, spec_path):
    room = spec["room"]
    L, W, H = room["length"], room["width"], room["height"]
    t, ft = room["wall_thickness"], room["floor_thickness"]
    mu, mu2 = room.get("mu", 1.0), room.get("mu2", 1.0)

    bodies = []
    # Floor top at z = 0, matching the reconstruction's floor.
    bodies.append(
        box("floor", (L / 2.0, W / 2.0, -ft / 2.0), (L + 2 * t, W + 2 * t, ft),
            FLOOR_COLOUR, mu, mu2)
    )
    for wall in WALLS:
        for name, centre, size in wall_segments(wall, room, spec["openings"]):
            bodies.append(box(name, centre, size, WALL_COLOUR, mu, mu2))
    if room["include_ceiling"]:
        bodies.append(
            box("ceiling", (L / 2.0, W / 2.0, H + t / 2.0), (L + 2 * t, W + 2 * t, t),
                CEILING_COLOUR, mu, mu2)
        )

    for i, f in enumerate(spec["furniture"]):
        name = f.get("name") or f"furniture{i}"
        try:
            sx, sy, sz = (float(v) for v in f["size"])
            pose = [float(v) for v in f["pose"]]
        except (KeyError, TypeError, ValueError):
            die(f"furniture '{name}': needs size [x,y,z] and pose [x,y,z] (+ optional yaw)")
        if len(pose) not in (3, 4):
            die(f"furniture '{name}': pose must be [x,y,z] or [x,y,z,yaw]")
        yaw = pose[3] if len(pose) == 4 else 0.0
        # Proposal S4.4.2: furniture in the standard branch is its bounding shape. That
        # is the point of the comparison -- the reconstruction recovers the real surface,
        # this does not. A pole or round table's bounding shape is a cylinder, not a box.
        if furniture_shape(f, name) == "cylinder":
            bodies.append(
                cylinder(name, pose[:3], sx, sz, FURNITURE_COLOUR, mu, mu2)
            )
        else:
            bodies.append(
                box(name, pose[:3], (sx, sy, sz), FURNITURE_COLOUR, mu, mu2, yaw)
            )

    return STANDARD_MODEL.format(
        spec=spec_path.name,
        when=time.strftime("%Y-%m-%d %H:%M:%S"),
        bodies="".join(bodies),
    ), len(bodies)


