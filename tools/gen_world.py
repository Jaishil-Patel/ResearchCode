#!/usr/bin/env python3
"""Generate both experiment branches from one template (proposal Task 3).

    python3 tools/gen_world.py --room lab_a --branch both
    python3 tools/gen_world.py --room lab_a --check      # prove they only differ by one line

Writes into `ros2_ws/src/pepper_room_description/`:

    models/room_standard/model.sdf     from the tape measurements, as primitives
    worlds/room_photogrammetry.sdf     |  same template,
    worlds/room_standard.sdf           |  different <include>

Proposal S4.4.2 makes the geometry source the *only* independent variable. Two worlds
maintained by hand drift -- a light moved here, a physics step size tweaked there -- and
once they differ in a second respect the comparison no longer measures photogrammetry
and the whole experiment is uninterpretable. So there is one template and one generator,
and `--check` exists to prove after every regeneration that the only difference is the
model being included.

The standard branch is built from `simulation/photogrammetry/ground_truth/<room>_spec.yaml`,
which is derived from the same tape measurements that gate the photogrammetric branch.
S4.4.2 requires it to be metrically faithful rather than eyeballed, which is why it is
generated from the measurement file rather than hand-authored in SDF.


Note on the floor
-----------------
There is deliberately no ground plane in the world template. Each branch supplies its own
floor -- a flat box in the standard branch, the reconstructed surface in the
photogrammetric one -- because the floor is geometry, and geometry is the thing being
compared. Dropping a shared flat plane at z=0 into both worlds would quietly erase one of
the differences the experiment exists to measure. `--debug-ground-plane` adds one anyway,
for the case where you are triaging a robot falling through a hole in the reconstruction.
"""

import argparse
import difflib
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GT_DIR = REPO / "simulation" / "photogrammetry" / "ground_truth"
PKG = REPO / "ros2_ws" / "src" / "pepper_room_description"

WALLS = ("x_min", "x_max", "y_min", "y_max")


def die(msg):
    print("ERROR: " + msg, file=sys.stderr)
    sys.exit(1)


def rel(path):
    """Repo-relative for readability, absolute when the path is outside the repo
    (--out can point anywhere, and the self-test points it at a temp directory)."""
    path = Path(path)
    try:
        return path.relative_to(REPO)
    except ValueError:
        return path


